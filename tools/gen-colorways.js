// data/colorways.json → theme/snippets/colorway-data.liquid
// Output for a handle: "label~material~hex1,hex2~sibling1,sibling2" (empty when unknown).
// The theme prefers product metafields (zayou.colorway, zayou.siblings) when the store has them; this map is the fallback.
// Re-run `node tools/build-catalog.js && node tools/gen-colorways.js` after adding or renaming products.
const fs = require('fs'); const path = require('path');
const map0 = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/colorways.json'), 'utf8'));
const clean = s => String(s || '').replace(/[~|§=]/g, ' ');
// One lookup string instead of a case per product (keeps Liquid complexity flat): "§handle=label~material~hexes~siblings"
let map = ''; let n = 0;
for (const [h, c] of Object.entries(map0)) {
  if (!c.label && !c.siblings.length) continue;
  map += '§' + h + '=' + [clean(c.label), clean(c.material), c.hex.join(','), c.siblings.join(',')].join('~'); n++;
}
const lines = [
  '{%- comment -%} GENERATED by tools/gen-colorways.js from the catalogue titles — do not edit by hand. Output: label~material~hexes~siblings {%- endcomment -%}',
  '{%- capture zy_key -%}§{{ handle }}={%- endcapture -%}',
  "{%- assign zy_map = '" + map.replace(/'/g, '’') + "' | split: zy_key -%}",
  "{%- if zy_map.size > 1 -%}{{ zy_map[1] | split: '§' | first }}{%- endif -%}",
];
fs.writeFileSync(path.join(__dirname, '../theme/snippets/colorway-data.liquid'), lines.join('\n') + '\n');
console.log('colorway-data.liquid:', n, 'products');
